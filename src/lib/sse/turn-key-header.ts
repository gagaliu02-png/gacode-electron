// =========================================================================
// turn-key-header —— 从 SSE **响应头**里取「这一轮的身份」 (契约订正 17)
// -------------------------------------------------------------------------
// 为什么要有这个文件
//
//   v2 (契约订正 16) 把「是不是同一轮」从「猜」改成「认」—— 服务端给一个
//   权威的 `turnKey` (`tk_xxx`):
//     · 流式帧的**顶层** `turnKey`  ⇒ 第一帧就有;
//     · 历史行的 `metadata.turnKey` ⇒ 落库后回看还是同一个值。
//
//   但**第一帧之前**有个 3~20 秒的窗口 (TTFT): 服务端**一个数据帧都不发**,
//   而客户端可能在这段窗口里被杀 (切后台 / 锁屏回收 / 手滑退页面)。
//   ⇒ 客户端「知道有这一轮」, 却「不知道这一轮是谁」⇒
//     回来时历史里那条服务端行带 turnKey, 本地那行没有 ⇒ 认不出亲
//     ⇒ 屏幕上两个气泡 (空气泡) + 本地那行永远收不到结尾 ⇒ 停止键永久顶亮。
//
//   服务端在 `reply.hijack()` 之后**立刻**把 `X-Turn-Key` 写进响应头 (毫秒级)
//   ⇒ 这个窗口被彻底堵上。
//
//   ⛔ 端侧只读**同一条**规则 (本文件) —— web / PC / 安卓各抄一份, 行为一致。
//
// ⛔ 本文件**不许** import window / fetch / js-cookie —— PC 要抄这份定稿。
//    零依赖 + 零 import (类型也自己定义) ⇒ 整个 `src/lib/sse/` 目录可以
//    **原样整目录拷走**, 一个字都不用改。
// =========================================================================

// =========================================================================
// 常量
// =========================================================================

/**
 * 响应头名字 (**小写**)。
 *
 * ⚠️ `Headers.get()` 本来就大小写不敏感 —— 这里固定小写只是为了**全端一个字符串**,
 *   免得 web 写 `X-Turn-Key`、PC 写 `x-turn-key`、安卓写 `X-TURN-KEY`，
 *   哪天有人手抄错一个字母就静默失效 (读不到 ⇒ 回落老路径 ⇒ 空气泡复发, 且极难查)。
 */
export const TURN_KEY_HEADER = "x-turn-key";

// =========================================================================
// 判据
// =========================================================================

/**
 * 从 SSE 响应头里取这一轮的 turnKey.
 *
 * @param headers  形如 `Headers` 的对象 (只需要 `.get(name)`)
 * @returns 这一轮的 turnKey; **取不到时返回 null** (老服务端没有这个头)
 *
 * ## 判据 (只有一条, 别加第二条)
 *
 *   · 头存在、且去掉首尾空白后**非空** ⇒ 返回它 (只去空白, 不改内容);
 *   · 否则 ⇒ null。
 *
 * ⛔ **不许**在这里校验 `tk_` 前缀 —— 那是**服务端**的格式约定,
 *   端上拿到什么就用什么: 万一服务端改前缀, 不该让端侧认不出这一轮。
 *   (前缀对不对由服务端自己保证 —— 它的测试会钉住。)
 *
 * ⛔ **不许**在这里「猜」: 头不存在就是「服务端没给」⇒ null ⇒
 *   端侧回落「帧顶层 turnKey」的老路径 (行为跟改之前逐字一致)。
 */
export function readTurnKeyHeader(
  headers: { get(name: string): string | null } | null | undefined,
): string | null {
  if (!headers || typeof headers.get !== "function") return null;
  let raw: string | null;
  try {
    raw = headers.get(TURN_KEY_HEADER);
  } catch (_: unknown) {
    // 头对象有问题 (老浏览器 / 测试桩) ⇒ 当「服务端没给」, 不许把整个流搞崩。
    return null;
  }
  if (typeof raw !== "string") return null;
  const v = raw.trim();
  return v.length > 0 ? v : null;
}
