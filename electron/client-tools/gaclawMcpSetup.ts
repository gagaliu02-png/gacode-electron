/**
 * gaclawMcpSetup.ts —— PC 客户端启动时，自动把 gaclaw MCP 工具注册到 Claude Code user scope。
 *
 * [T-142] 目标：链路统一。
 *   VC 插件会话 / CLI 会话 / pc_cc_new 新建的 cli-bg 会话，都看到同一个工具：
 *     mcp__gaclaw__send
 *
 * 为什么不用 MCP SDK：当前 PC 仓没有 @modelcontextprotocol/sdk 依赖。
 * MCP stdio 本质就是进程 stdin/stdout 的 JSON-RPC 行协议；这里实现一个**最小可用**
 * stdio server，只暴露 send 工具，通过现有本机 hook bridge `/cc-tools/send` 回信。
 *
 * 设计约束：
 *   - launcher 写到稳定路径 ~/.gaclaw/mcp/gaclaw-msg-mcp.mjs，不随安装包版本漂移；
 *   - 只改 ~/.claude.json 的 mcpServers.gaclaw 与 ~/.claude/settings.json 的 permissions.allow；
 *   - 改前备份、解析失败不写、幂等；
 *   - 不删除用户其它配置，卸载 PC 也不自动清理（避免工具突然消失）。
 */

import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

export const MCP_SERVER_NAME = 'gaclaw';
export const MCP_TOOL_NAME = 'mcp__gaclaw__send';

/** 稳定 launcher 路径（不随安装包版本变）。 */
export function gaclawMcpDir(): string {
  return path.join(os.homedir(), '.gaclaw', 'mcp');
}
export function gaclawMcpLauncherPath(): string {
  return path.join(gaclawMcpDir(), `${MCP_SERVER_NAME}-msg-mcp.mjs`);
}
export function claudeJsonPath(): string {
  return path.join(os.homedir(), '.claude.json');
}
export function claudeSettingsPath(): string {
  return path.join(os.homedir(), '.claude', 'settings.json');
}

/**
 * 最小 MCP stdio server 源码（launcher 内容）。
 * 只实现：initialize / tools/list / tools/call。
 * 工具：send —— 调本机 hook bridge 的 /cc-tools/send。
 */
export const MCP_SERVER_SOURCE = String.raw`#!/usr/bin/env node
// Generated by Gacode. Stable launcher for Claude Code user-scope MCP server.
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';

const MARKER = 'gaclaw-hook-bridge';
const TOOL = 'send';

function readJson(file) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch { return null; }
}
function findHookConnection() {
  const files = [
    path.join(os.homedir(), '.claude', 'settings.local.json'),
    path.join(os.homedir(), '.claude', 'settings.json'),
  ];
  for (const file of files) {
    const data = readJson(file);
    const events = data && data.hooks;
    if (!events || typeof events !== 'object') continue;
    for (const arr of Object.values(events)) {
      if (!Array.isArray(arr)) continue;
      for (const entry of arr) {
        for (const h of Array.isArray(entry && entry.hooks) ? entry.hooks : []) {
          const url = h && typeof h.url === 'string' ? h.url : '';
          if (!url.includes(MARKER)) continue;
          try {
            const u = new URL(url);
            const token = u.searchParams.get('token') || '';
            if (!token || (u.hostname !== '127.0.0.1' && u.hostname !== 'localhost' && u.hostname !== '[::1]')) continue;
            return { base: u.protocol + '//' + u.host, token };
          } catch { /* skip */ }
        }
      }
    }
  }
  return null;
}

function respond(id, result) {
  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id, result }) + '\n');
}
function respondError(id, code, message) {
  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id, error: { code, message } }) + '\n');
}
function toolDescriptor() {
  return {
    name: TOOL,
    description: '主动给 Gacode/Cody 业务会话发一条消息（agent_message，不冒用户气泡）。用于 report_when_idle 按 reply_to 主动回报。',
    inputSchema: {
      type: 'object',
      properties: {
        toSessionId: { type: 'string', minLength: 1, description: '业务会话 id（优先取 reply_to_business_session_id）' },
        content: { type: 'string', minLength: 1, maxLength: 8000, description: '回报正文' },
        taskId: { type: 'string', description: '可选：任务/投递幂等 id' },
        replyTo: {
          type: 'object',
          properties: {
            taskId: { type: 'string' },
            ccSessionId: { type: 'string' },
            businessSessionId: { type: 'string' },
            channel: { type: 'string' },
          },
          additionalProperties: false,
        },
        replyToTaskId: { type: 'string' },
        replyToCcSessionId: { type: 'string' },
        replyToBusinessSessionId: { type: 'string' },
        replyChannel: { type: 'string' },
        idempotencyKey: { type: 'string' },
      },
      required: ['toSessionId', 'content'],
      additionalProperties: false,
    },
  };
}
function buildBody(a) {
  if (!a || typeof a !== 'object') throw new Error('arguments 必须是对象');
  const to = String(a.toSessionId || '').trim();
  const content = String(a.content || '').trim();
  if (!to) throw new Error('缺少 toSessionId');
  if (!content) throw new Error('缺少 content');
  const reply = a.replyTo && typeof a.replyTo === 'object' ? a.replyTo : {};
  const body = { toSessionId: to, content: content.slice(0, 8000) };
  const taskId = a.taskId || reply.taskId || a.replyToTaskId;
  const ccSessionId = reply.ccSessionId || a.replyToCcSessionId;
  const businessSessionId = reply.businessSessionId || a.replyToBusinessSessionId;
  const channel = reply.channel || a.replyChannel;
  if (taskId) body.taskId = String(taskId);
  if (ccSessionId) body.replyToCcSessionId = String(ccSessionId);
  if (businessSessionId) body.replyToBusinessSessionId = String(businessSessionId);
  if (channel) body.replyChannel = String(channel);
  if (a.idempotencyKey) body.idempotencyKey = String(a.idempotencyKey);
  return body;
}
async function callSend(args) {
  const conn = findHookConnection();
  if (!conn) throw new Error('找不到 gaclaw hook bridge 连接（未安装 hook 或 token 不可读）');
  const res = await fetch(conn.base + '/cc-tools/send?token=' + encodeURIComponent(conn.token), {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(buildBody(args)),
  });
  const text = await res.text();
  let data = null;
  try { data = text ? JSON.parse(text) : null; } catch { data = null; }
  if (!res.ok || !data || data.ok === false) {
    throw new Error('hook /cc-tools/send 失败: ' + (data && (data.message || data.error) ? (data.message || data.error) : ('HTTP ' + res.status)));
  }
  return {
    ok: true,
    inboxId: data.inboxId || null,
    delivered: !!data.delivered,
    accepted: !!data.accepted,
    queued: !!data.queued,
    duplicate: !!data.duplicate,
    activeTurn: !!data.activeTurn,
    serverTurnStarted: !!data.serverTurnStarted,
  };
}

let buf = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => {
  buf += chunk;
  let i;
  while ((i = buf.indexOf('\n')) >= 0) {
    const line = buf.slice(0, i).trim();
    buf = buf.slice(i + 1);
    if (!line) continue;
    void handleLine(line);
  }
});
async function handleLine(line) {
  let msg;
  try { msg = JSON.parse(line); } catch { return; }
  if (!msg || msg.jsonrpc !== '2.0') return;
  const id = msg.id;
  const method = String(msg.method || '');
  if (method === 'initialize') {
    const protocolVersion = msg.params && typeof msg.params.protocolVersion === 'string'
      ? msg.params.protocolVersion : '2024-11-05';
    respond(id, {
      protocolVersion,
      capabilities: { tools: { listChanged: false } },
      serverInfo: { name: 'gaclaw', version: '1.0.0' },
    });
    return;
  }
  if (method === 'notifications/initialized' || method === 'initialized') return;
  if (method === 'ping') { respond(id, {}); return; }
  if (method === 'tools/list') { respond(id, { tools: [toolDescriptor()] }); return; }
  if (method === 'tools/call') {
    const params = msg.params || {};
    if (params.name !== TOOL) { respondError(id, -32602, 'unknown tool: ' + String(params.name)); return; }
    try {
      const r = await callSend(params.arguments || {});
      respond(id, { content: [{ type: 'text', text: JSON.stringify(r) }], isError: false });
    } catch (e) {
      respond(id, { content: [{ type: 'text', text: String(e && e.message ? e.message : e) }], isError: true });
    }
    return;
  }
  if (id !== undefined && id !== null) respondError(id, -32601, 'method not found: ' + method);
}
process.stdin.on('end', () => process.exit(0));
`;

/** 纯函数：幂等设置 ~/.claude.json 的 mcpServers.gaclaw。 */
export function upsertMcpServersConfig(parsed: Record<string, any>, launcherPath: string): {
  data: Record<string, any>;
  changed: boolean;
} {
  const data = parsed && typeof parsed === 'object' ? parsed : {};
  const servers = data.mcpServers && typeof data.mcpServers === 'object' ? data.mcpServers : {};
  const desired = { command: 'node', args: [launcherPath] };
  const current = servers[MCP_SERVER_NAME];
  const same = current
    && current.command === desired.command
    && Array.isArray(current.args)
    && current.args.length === desired.args.length
    && current.args.every((x: unknown, i: number) => x === desired.args[i]);
  if (same) return { data, changed: false };
  servers[MCP_SERVER_NAME] = desired;
  data.mcpServers = servers;
  return { data, changed: true };
}

/** 纯函数：幂等设置 permissions.allow 中的 mcp__gaclaw__send。 */
export function upsertPermissionsAllow(parsed: Record<string, any>, toolName = MCP_TOOL_NAME): {
  data: Record<string, any>;
  changed: boolean;
} {
  const data = parsed && typeof parsed === 'object' ? parsed : {};
  const permissions = data.permissions && typeof data.permissions === 'object' ? data.permissions : {};
  const allow = Array.isArray(permissions.allow) ? permissions.allow.slice() : [];
  if (allow.includes(toolName)) return { data, changed: false };
  allow.push(toolName);
  permissions.allow = allow;
  data.permissions = permissions;
  return { data, changed: true };
}

function writeJsonIfChanged(file: string, parsed: Record<string, any>, changed: boolean): void {
  if (!changed) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  try {
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    fs.copyFileSync(file, `${file}.bak.${stamp}`);
  } catch { /* 文件不存在 / 备份失败不阻断首次写入 */ }
  const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
  fs.writeFileSync(tmp, JSON.stringify(parsed, null, 2) + '\n', 'utf8');
  fs.renameSync(tmp, file);
}

/** PC 启动时调用：写 launcher + 注册 user scope MCP + 放行工具。失败只返回 ok:false，不抛。 */
export function ensureGaclawMcpConfigured(): { ok: boolean; changed: boolean; errors: string[] } {
  const errors: string[] = [];
  let changed = false;
  try {
    const dir = gaclawMcpDir();
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
    const launcher = gaclawMcpLauncherPath();
    if (!fs.existsSync(launcher) || fs.readFileSync(launcher, 'utf8') !== MCP_SERVER_SOURCE) {
      fs.writeFileSync(launcher, MCP_SERVER_SOURCE, { encoding: 'utf8', mode: 0o700 });
      changed = true;
    }
    try { fs.chmodSync(launcher, 0o700); } catch { /* Windows 忽略 */ }

    const cjPath = claudeJsonPath();
    const cjRaw = fs.existsSync(cjPath) ? fs.readFileSync(cjPath, 'utf8') : '{}';
    let cjParsed: Record<string, any> = {};
    try { cjParsed = cjRaw.trim() ? JSON.parse(cjRaw) : {}; } catch (e) {
      errors.push('~/.claude.json 解析失败，未修改: ' + (e as Error).message);
    }
    if (!errors.some((x) => x.includes('~/.claude.json'))) {
      const r = upsertMcpServersConfig(cjParsed, launcher);
      if (r.changed) { writeJsonIfChanged(cjPath, r.data, true); changed = true; }
    }

    const stPath = claudeSettingsPath();
    const stRaw = fs.existsSync(stPath) ? fs.readFileSync(stPath, 'utf8') : '{}';
    let stParsed: Record<string, any> = {};
    try { stParsed = stRaw.trim() ? JSON.parse(stRaw) : {}; } catch (e) {
      errors.push('~/.claude/settings.json 解析失败，未修改: ' + (e as Error).message);
    }
    if (!errors.some((x) => x.includes('~/.claude/settings.json'))) {
      const r = upsertPermissionsAllow(stParsed);
      if (r.changed) { writeJsonIfChanged(stPath, r.data, true); changed = true; }
    }
  } catch (e) {
    errors.push((e as Error).message || String(e));
  }
  return { ok: errors.length === 0, changed, errors };
}
